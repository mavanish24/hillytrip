export function getCategoryFromSemanticText(text: string): ImageCategory {
  const norm = (text || '').toLowerCase();
  if (norm.includes('tea') || norm.includes('garden')) return 'teaGarden';
  if (norm.includes('monastery') || norm.includes('temple') || norm.includes('church')) return 'monastery';
  if (norm.includes('waterfall') || norm.includes('falls')) return 'waterfall';
  if (norm.includes('lake') || norm.includes('tso')) return 'lake';
  if (norm.includes('wildlife') || norm.includes('bird') || norm.includes('animal')) return 'wildlife';
  if (norm.includes('food') || norm.includes('dining')) return 'food';
  if (norm.includes('taxi') || norm.includes('stand') || norm.includes('cab')) return 'taxi';
  if (norm.includes('forest') || norm.includes('pine') || norm.includes('jungle')) return 'forest';
  if (norm.includes('homestay') || norm.includes('village') || norm.includes('stay')) return 'village';
  return 'mountain';
}

export function getDeterministicDefaultImage(seed: string, category?: ImageCategory, targetWidth = 400): string {
  const cat = category || getCategoryFromSemanticText(seed);
  const pool = DEFAULT_IMAGES[cat] || DEFAULT_IMAGES.mountain;
  let hash = 0;
  for (let i = 0; i < seed.length; i++) hash = (hash << 5) - hash + seed.charCodeAt(i);
  return pool[Math.abs(hash) % pool.length] || COMMON_STORAGE_ASSETS.defaultFallback;
}
