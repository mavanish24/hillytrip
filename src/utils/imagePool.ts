/**
 * Core image optimizer and sanitizer.
 * Guarantees that no missing, placeholder, or third-party/Unsplash image is returned.
 * Always resolves to high-quality Supabase Storage assets.
 */
export function getOptimizedImageUrl(url?: string, targetWidth = 400): string {
  if (!url || typeof url !== 'string' || url.trim() === '') {
    return COMMON_STORAGE_ASSETS.defaultFallback;
  }

  const cleanUrl = url.trim();

  // If already a valid Supabase Storage public URL
  if (cleanUrl.includes('supabase.co/storage/v1/object/public/')) {
    return cleanUrl;
  }

  // If it's a legacy SVG fallback in /images/hillytrip/
  if (cleanUrl.startsWith('/images/hillytrip/')) {
    if (cleanUrl.includes('homestay')) return HOMESTAY_STORAGE_ASSETS.woodenExterior;
    if (cleanUrl.includes('tea-garden')) return DESTINATION_STORAGE_ASSETS.teaGardenVillage;
    if (cleanUrl.includes('monastery')) return ATTRACTION_STORAGE_ASSETS.monastery;
    if (cleanUrl.includes('lake')) return ATTRACTION_STORAGE_ASSETS.lake;
    if (cleanUrl.includes('forest')) return DESTINATION_STORAGE_ASSETS.foggyPineForest;
    if (cleanUrl.includes('wildlife')) return ATTRACTION_STORAGE_ASSETS.wildlife;
    if (cleanUrl.includes('food')) return HOMESTAY_STORAGE_ASSETS.localFoodDining;
    if (cleanUrl.includes('taxi')) return TAXI_STAND_STORAGE_ASSETS.himalayanTaxiStand;
    return COMMON_STORAGE_ASSETS.defaultFallback;
  }

  // Intercept any third-party sample / Unsplash / external stock images
  if (cleanUrl.includes('images.unsplash.com') || cleanUrl.includes('pexels.com') || cleanUrl.includes('pixabay.com') || cleanUrl.includes('placeholder')) {
    return getDestinationImage(cleanUrl, '', '');
  }

  // Valid local paths or data URIs
  if (cleanUrl.startsWith('/') || cleanUrl.startsWith('data:')) {
    return cleanUrl;
  }

  return cleanUrl;
}

/**
 * Backwards compatible helper returning an appropriate HillyTrip Supabase image for any entity.
 */
export function getSmartDirectUnsplashUrl(name: string, description: string, categoryOrType: string, targetWidth = 400): string {
  const combined = `${name || ''} ${description || ''} ${categoryOrType || ''}`;
  const norm = combined.toLowerCase();

  // Check if it's a homestay
  if (norm.includes('homestay') || norm.includes('resort') || norm.includes('lodge') || norm.includes('cottage') || norm.includes('inn') || norm.includes('retreat')) {
    return getHomestayImage(name, categoryOrType);
  }

  // Check if it's a taxi stand / route transit
  if (norm.includes('taxi') || norm.includes('cab') || norm.includes('transit') || norm.includes('stand') || norm.includes('syndicate') || norm.includes('hub')) {
    return getTaxiStandImage(name, categoryOrType);
  }

  // Check if it's an attraction / sightseeing spot
  if (
    norm.includes('waterfall') || norm.includes('falls') ||
    norm.includes('viewpoint') || norm.includes('view point') || norm.includes('sunrise') || norm.includes('sunset') ||
    norm.includes('monastery') || norm.includes('temple') || norm.includes('gompa') || norm.includes('stupa') || norm.includes('church') ||
    norm.includes('lake') || norm.includes('tso') || norm.includes('pokhri') ||
    norm.includes('zoo') || norm.includes('sanctuary') || norm.includes('safari') || norm.includes('wildlife') || norm.includes('bird') ||
    norm.includes('bazaar') || norm.includes('market') || norm.includes('museum') ||
    norm.includes('bridge') || norm.includes('cave') || norm.includes('hot spring') || norm.includes('trek') || norm.includes('hiking')
  ) {
    return getAttractionImage(name, categoryOrType);
  }

  // Default to Destination / Village image
  return getDestinationImage(name, categoryOrType);
}

