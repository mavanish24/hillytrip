/**
 * Intelligent Taxi Stand Image Resolver
 * Priority: Major Town -> Himalayan Hill Stand -> Shared Taxi -> Mountain Road -> Transit Fallback
 */
export function getTaxiStandImage(standOrName?: any, type?: string, districtOrRegion?: string): string {
  const name = typeof standOrName === 'object' && standOrName ? (standOrName.name || standOrName.standName || '') : String(standOrName || '');
  const t = typeof standOrName === 'object' && standOrName ? (standOrName.type || type || '') : String(type || '');
  const dist = typeof standOrName === 'object' && standOrName ? (standOrName.district || standOrName.region || districtOrRegion || '') : String(districtOrRegion || '');

  const text = sanitize(`${name} ${t} ${dist}`);

  if (text.includes('siliguri') || text.includes('njp') || text.includes('bagdogra') || text.includes('gangtok') || text.includes('darjeeling') || text.includes('kalimpong') || text.includes('major') || text.includes('city') || text.includes('junction')) {
    return TAXI_STAND_STORAGE_ASSETS.majorHillTownTaxiStand;
  }
  if (text.includes('shared') || text.includes('bolero') || text.includes('sumo') || text.includes('pool') || text.includes('syndicate')) {
    return TAXI_STAND_STORAGE_ASSETS.sharedTaxi;
  }
  if (text.includes('pass') || text.includes('nh10') || text.includes('highway') || text.includes('corridor') || text.includes('mountain road') || text.includes('ghat')) {
    return TAXI_STAND_STORAGE_ASSETS.mountainRoad;
  }
  if (text.includes('village') || text.includes('ghoom') || text.includes('kurseong') || text.includes('jorethang') || text.includes('melli') || text.includes('rangpo') || text.includes('singtam') || text.includes('pelling') || text.includes('lachen') || text.includes('lachung')) {
    return TAXI_STAND_STORAGE_ASSETS.himalayanTaxiStand;
  }

  return TAXI_STAND_STORAGE_ASSETS.himalayanTaxiStand;
}

